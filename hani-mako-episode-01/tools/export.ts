// Builds the timeline from the cue sheet + audio manifest and writes:
//   build/timeline.json            (consumed by tools/build_audio.py mix)
//   out/hani-mako-ep01.vi.srt      (Vietnamese captions aligned to the actual clips)
//   docs/timing.md                 (generated cue/timing table)
// Then runs the strawberry continuity and lesson checks. Exit code 1 on failure.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { evaluate } from '../src/episode01/evaluate.ts';
import { PLATE_SLOTS, SIDS, type SId } from '../src/episode01/layout.ts';
import { berryStates, buildTimeline, FPS, type Manifest, type Timeline } from '../src/episode01/timeline.ts';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const manifest = JSON.parse(fs.readFileSync(path.join(ROOT, 'src/generated/audio-manifest.json'), 'utf8')) as Manifest;
const tl: Timeline = buildTimeline(manifest);

// ───────────────────────── timeline.json (audio mix input)
fs.mkdirSync(path.join(ROOT, 'build'), { recursive: true });
fs.writeFileSync(
  path.join(ROOT, 'build/timeline.json'),
  JSON.stringify(
    {
      fps: tl.fps,
      totalFrames: tl.totalFrames,
      speech: tl.speech.map((s) => ({ lineId: s.lineId, file: s.file, start: s.start, frames: s.frames })),
      sfx: tl.sfx,
      music: tl.music,
      cues: tl.cues.map(({ id, beat, start, end }) => ({ id, beat, start, end })),
    },
    null,
    1,
  ),
);

// ───────────────────────── SRT
const ts = (frame: number) => {
  const ms = Math.round((frame / FPS) * 1000);
  const h = Math.floor(ms / 3600000);
  const m = Math.floor((ms % 3600000) / 60000);
  const s = Math.floor((ms % 60000) / 1000);
  const r = ms % 1000;
  const p = (n: number, w = 2) => String(n).padStart(w, '0');
  return `${p(h)}:${p(m)}:${p(s)},${p(r, 3)}`;
};
type Cap = { start: number; end: number; text: string };
const caps: Cap[] = [];
for (const c of tl.cues) {
  const sp = tl.speech.filter((s) => s.cue === c.id);
  if (!sp.length) continue;
  if (sp.length === 1) caps.push({ start: sp[0].start, end: sp[0].start + sp[0].frames, text: sp[0].text });
  else {
    const words = sp.map((s, i) => {
      const w = s.text.replace(/[.!]/g, '');
      return i === 0 ? w : w.toLowerCase();
    });
    const last = sp[sp.length - 1];
    caps.push({ start: sp[0].start, end: last.start + last.frames, text: `${words.join(', ')}.` });
  }
}
// keep captions readable: minimum 1.0 s on screen, never overlapping the next one
caps.forEach((c, i) => {
  const next = caps[i + 1];
  c.end = Math.max(c.end + 6, c.start + 30);
  if (next) c.end = Math.min(c.end, next.start - 2);
});
fs.mkdirSync(path.join(ROOT, 'out'), { recursive: true });
fs.writeFileSync(
  path.join(ROOT, 'out/hani-mako-ep01.vi.srt'),
  caps.map((c, i) => `${i + 1}\n${ts(c.start)} --> ${ts(c.end)}\n${c.text}\n`).join('\n'),
);

// ───────────────────────── timing doc
const fmt = (f: number) => `${Math.floor(f / FPS / 60)}:${((f / FPS) % 60).toFixed(1).padStart(4, '0')}`;
const md = [
  '# Episode 01 — generated timing sheet',
  '',
  `Generated by \`npm run export\` from \`src/episode01/cues.ts\` and the measured audio. Total: **${(tl.totalFrames / FPS).toFixed(2)} s** (${tl.totalFrames} frames @ ${FPS} fps).`,
  '',
  '| # | Beat | Cue | Start | Dur | Shot | Dialogue | Action |',
  '|---|---|---|---|---|---|---|---|',
  ...tl.cues.map((c, i) => {
    const sp = tl.speech.filter((s) => s.cue === c.id);
    const text = sp.length > 1 ? caps.find((k) => k.start === sp[0].start)?.text : sp[0]?.text;
    const who = sp[0] ? (sp[0].who.length > 1 ? 'Hani + Mako' : sp[0].who[0] === 'hani' ? 'Hani' : 'Mako') : '';
    return `| ${i + 1} | ${c.beat} | ${c.id} | ${fmt(c.start)} | ${((c.end - c.start) / FPS).toFixed(1)} s | ${c.shot} | ${
      text ? `**${who}:** ${text}` : '—'
    } | ${c.note.replace(/\|/g, '/')} |`;
  }),
  '',
];
fs.mkdirSync(path.join(ROOT, 'docs'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'docs/timing.md'), md.join('\n'));

// ───────────────────────── continuity + lesson checks
const fails: string[] = [];
const ok: string[] = [];
const check = (cond: boolean, msg: string) => (cond ? ok : fails).push(msg);

const contents = (f: number) => {
  const st = berryStates(tl, f);
  const by = { bowl: [] as SId[], hani: [] as SId[], mako: [] as SId[], moving: [] as SId[] };
  for (const b of st) {
    if (b.at === 'moving') by.moving.push(b.id);
    else if (b.loc.kind === 'bowl') by.bowl.push(b.id);
    else by[b.loc.owner].push(b.id);
  }
  return { st, by };
};
const same = (a: SId[], b: SId[]) => a.length === b.length && [...a].sort().join() === [...b].sort().join();
const cueById = (id: string) => tl.cues.find((c) => c.id === id)!;

// 1. inventory is exactly six at every frame, no shared slots, no visual overlaps
let invOk = true;
let slotOk = true;
let overlapOk = true;
let minGap = Infinity;
for (let f = 0; f < tl.totalFrames; f++) {
  const { st, by } = contents(f);
  const total = by.bowl.length + by.hani.length + by.mako.length + by.moving.length;
  if (total !== 6 || new Set(st.map((s) => s.id)).size !== 6) invOk = false;
  const keys = st.filter((s) => s.at !== 'moving').map((s) => JSON.stringify(s.loc));
  if (new Set(keys).size !== keys.length) slotOk = false;
  if (f % 3 === 0) {
    const v = evaluate(tl, manifest, f);
    const settled = v.berries.filter((b) => b.layer !== 'top');
    for (let i = 0; i < settled.length; i++)
      for (let j = i + 1; j < settled.length; j++) {
        const d = Math.hypot(settled[i].x - settled[j].x, settled[i].y - settled[j].y);
        minGap = Math.min(minGap, d);
        if (d < 48) overlapOk = false;
      }
  }
}
check(invOk, 'Inventory: exactly six unique strawberries (S1–S6) at every frame, including carried ones');
check(slotOk, 'No two settled strawberries ever share a slot');
check(overlapOk, `No overlapping settled strawberries (minimum centre distance ${minGap.toFixed(0)} px ≥ 48 px)`);

// 2. state checkpoints
const s0 = contents(0).by;
check(same(s0.bowl, SIDS) && !s0.hani.length && !s0.mako.length, 'Initial: bowl = S1..S6');
const afterShare = contents(cueById('share').end).by;
check(
  same(afterShare.hani, ['S1', 'S2', 'S3', 'S4']) && same(afterShare.mako, ['S5', 'S6']) && afterShare.bowl.length === 0,
  `After distribution: Hani = S1,S2,S3,S4 / Mako = S5,S6 / bowl empty (got H=${afterShare.hani} M=${afterShare.mako} B=${afterShare.bowl})`,
);
const fix = cueById('move');
const afterFix = contents(fix.end).by;
check(
  same(afterFix.hani, ['S1', 'S2', 'S3']) && same(afterFix.mako, ['S4', 'S5', 'S6']) && afterFix.bowl.length === 0,
  `After correction: Hani = S1,S2,S3 / Mako = S4,S5,S6 (got H=${afterFix.hani} M=${afterFix.mako})`,
);
const fixTransfers = tl.transfers.filter((t) => t.start >= fix.start && t.start < fix.end);
check(
  fixTransfers.length === 1 &&
    fixTransfers[0].id === 'S4' &&
    fixTransfers[0].from.kind === 'plate' &&
    fixTransfers[0].from.owner === 'hani' &&
    fixTransfers[0].to.kind === 'plate' &&
    fixTransfers[0].to.owner === 'mako',
  'Correction moves exactly ONE strawberry (S4) from Hani\'s plate to Mako\'s plate',
);
const shotKeysInFix = tl.shots.filter((s) => s.frame > fixTransfers[0].start && s.frame <= fixTransfers[0].end);
check(shotKeysInFix.length === 0, 'No camera cut or camera move starts during the correction transfer');
const ease = tl.shots.find((s) => s.frame === fix.start);
check(!ease || ease.frame + ease.ease <= fixTransfers[0].start, 'Camera is settled before the correction transfer begins');
check(tl.transfers.length === 7, `Total transfers = 7 (6 distribution + 1 correction), got ${tl.transfers.length}`);

// 3. counting agrees with what is on the plate
for (const id of ['countM1', 'countH1', 'countH2', 'countM2']) {
  const c = cueById(id);
  const marks = tl.counts.filter((m) => m.frame >= c.start && m.frame < c.end);
  const who = marks[0].who;
  const plate = contents(marks[0].frame).by[who];
  const ids = marks.map((m) => m.id);
  const nums = marks.map((m) => m.n);
  const spoken = marks.map((m) => manifest.lines[m.wordId].text);
  check(
    same(ids, plate) && new Set(ids).size === ids.length && nums.join() === ids.map((_, i) => i + 1).join(),
    `${id}: ${who} counts ${spoken.join(' ')} over [${ids}] = plate contents [${plate}] (each highlighted once)`,
  );
}
// 4. badges match plate counts
for (const b of tl.badges) {
  if (b.n === null) continue;
  const n = contents(b.frame).by[b.who].length;
  check(n === b.n, `Badge ${b.who}=${b.n} at ${fmt(b.frame)} matches plate count ${n}`);
}
// 5. viewer pause
const think = cueById('think');
const speechInThink = tl.speech.filter((s) => s.start < think.end && s.start + s.frames > think.start);
const pauseState = contents(think.start).by;
check(
  (think.end - think.start) / FPS >= 4 && speechInThink.length === 0 && pauseState.hani.length === 4 && pauseState.mako.length === 2,
  `Viewer pause: ${((think.end - think.start) / FPS).toFixed(1)} s of silence on a 4-vs-2 hold`,
);
// 6. dialogue does not overlap
const sorted = [...tl.speech].sort((a, b) => a.start - b.start);
let overlapSpeech = 0;
for (let i = 1; i < sorted.length; i++) if (sorted[i].start < sorted[i - 1].start + sorted[i - 1].frames) overlapSpeech++;
check(overlapSpeech === 0, 'No overlapping dialogue clips');
// 7. runtime
const secs = tl.totalFrames / FPS;
check(secs >= 135 && secs <= 165, `Runtime ${secs.toFixed(2)} s is within 135–165 s`);
// 8. plate capacity
check(PLATE_SLOTS.hani.length >= 4 && PLATE_SLOTS.mako.length >= 3, 'Plate slots cover the needed counts');

const report = [
  `# Continuity & lesson check (${new Date().toISOString().slice(0, 10)})`,
  '',
  ...ok.map((m) => `- PASS — ${m}`),
  ...fails.map((m) => `- FAIL — ${m}`),
  '',
].join('\n');
fs.writeFileSync(path.join(ROOT, 'out/continuity-report.md'), report);
console.log(report);
console.log(`timeline: ${secs.toFixed(2)} s, ${tl.speech.length} clips, ${caps.length} captions`);
if (fails.length) process.exit(1);
